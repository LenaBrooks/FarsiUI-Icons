/**
 * Reads assets/logos-per-service/{Color|Mono}/*.svg
 * (zegond-style Iranian utility service marks) and emits catalog + modules.
 */
import { mkdir, readdir, readFile, writeFile, rm } from "node:fs/promises";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { optimize } from "svgo";
import { normalizeOpticalViewBox } from "./lib/optical-normalize.mjs";
import { brandColorsField } from "./lib/brand-colors.mjs";
import {
  flushComponentRegistry,claimComponentName,
  preferredIconName,
  unregisterIds,
} from "./lib/component-registry.mjs";


const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = join(root, "assets", "logos-per-service");
const outRoot = join(root, "src", "generated", "logos-per-service");

const CATEGORY = {
  id: "logos-per-service",
  prefix: "lps",
  labelEn: "Utility Services",
  labelFa: "خدمات شهری",
};

const NAME_FA = {
  electricity: "برق",
  gas: "گاز",
  post: "پست",
  telecom: "مخابرات",
  water: "آب",
};

const NAME_EN = {
  electricity: "Electricity",
  gas: "Gas",
  post: "Post",
  telecom: "Telecom",
  water: "Water",
};

function kebab(value) {
  return value
    .replace(/\.svg$/i, "")
    .replace(/_/g, "-")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
}

function pascal(value) {
  return value
    .split("-")
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

function makeMono(svg) {
  return svg.replace(
    /fill=("|')(?!none\1)[^"']+\1/gi,
    'fill="currentColor"',
  );
}

function optimizeSvg(svg, variant) {
  const input = variant === "mono" ? makeMono(svg) : svg;
  return optimize(input, {
    multipass: true,
    plugins: ["preset-default", "removeDimensions"],
  }).data;
}

function parseSvg(svg) {
  const viewBox = svg
    .match(/viewBox=["']([^"']+)["']/i)?.[1]
    ?.trim()
    .split(/[ ,]+/)
    .map(Number);
  if (!viewBox || viewBox.length !== 4 || viewBox.some(Number.isNaN)) {
    throw new Error("SVG is missing a valid viewBox");
  }
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/i, "")
    .replace(/<\/svg>[\s\S]*$/i, "")
    .replace(/<\?xml[\s\S]*?\?>/gi, "")
    .replace(/<(title|desc)\b[^>]*>[\s\S]*?<\/\1>/gi, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\sdata-name=("[^"]*"|'[^']*')/gi, "")
    // Keep gradient/clip ids — stripping them breaks fill="url(#…)".
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .trim();
  return {
    viewBox: viewBox.join(" "),
    width: viewBox[2],
    height: viewBox[3],
    body,
  };
}

function serialize(value) {
  return JSON.stringify(value);
}

const colorDir = join(sourceRoot, "Color");
const monoDir = join(sourceRoot, "Mono");
const colorFiles = (await readdir(colorDir))
  .filter((n) => n.toLowerCase().endsWith(".svg"))
  .sort();

if (colorFiles.length === 0) {
  throw new Error(`No SVGs found under ${colorDir}`);
}

unregisterIds((id) => id.startsWith("lps-"));

/** @type {Map<string, any>} */
const byId = new Map();

for (const file of colorFiles) {
  const slug = kebab(file);
  const id = `lps-${slug}`;
  const monoFile = join(monoDir, file);
  const colorSource = await readFile(join(colorDir, file), "utf8");
  let monoSource;
  try {
    monoSource = await readFile(monoFile, "utf8");
  } catch {
    throw new Error(`Missing mono twin for ${file}`);
  }

  const color = parseSvg(normalizeOpticalViewBox(optimizeSvg(colorSource, "color")));
  const mono = parseSvg(normalizeOpticalViewBox(optimizeSvg(monoSource, "mono")));
  const nameEn = NAME_EN[slug] ?? pascal(slug);
  const nameFa = NAME_FA[slug] ?? nameEn;
  const componentName = claimComponentName(preferredIconName(slug), id);

  byId.set(id, {
    id,
    slug,
    category: CATEGORY.id,
    nameEn,
    nameFa,
    componentName,
    color,
    mono,
  });
}

const icons = [...byId.values()].sort((a, b) => a.id.localeCompare(b.id));

await rm(outRoot, { recursive: true, force: true });
await mkdir(outRoot, { recursive: true });
await mkdir(join(outRoot, "icons"), { recursive: true });

const data = {};
for (const icon of icons) {
  data[icon.id] = { color: icon.color, mono: icon.mono };
}

await writeFile(
  join(outRoot, "data.ts"),
  `// Generated by scripts/generate-logos-per-service.mjs — do not edit.\n` +
    `import type { IconVariantData } from "../../types";\n\n` +
    `export const data: Record<string, IconVariantData> = ${serialize(data)};\n`,
);

const catalogEntries = icons.map((icon) => ({
  id: icon.id,
  nameFa: icon.nameFa,
  nameEn: icon.nameEn,
  componentName: icon.componentName,
  category: icon.category,
  source: "logos-per-service",
  sourceUrl: "https://github.com/zegond/logos-per-service",
  verificationStatus: "verified",
  notes:
    "SVG from logos-per-service (zegond). Color + mono utility service marks.",
  ...brandColorsField(icon.id),
  viewBox: icon.color.viewBox,
  aspectRatio: icon.color.width / icon.color.height,
}));

await writeFile(
  join(outRoot, "catalog.ts"),
  `// Generated by scripts/generate-logos-per-service.mjs — do not edit.\n` +
    `import type { IconCategoryMeta, IconManifestEntry } from "../../types";\n\n` +
    `export const logosPerServiceCategory: IconCategoryMeta = ${serialize({
      ...CATEGORY,
      count: icons.length,
    })};\n\n` +
    `export const logosPerServiceManifest: IconManifestEntry[] = ${serialize(catalogEntries)};\n`,
);

const lines = [
  `// Generated by scripts/generate-logos-per-service.mjs — do not edit.`,
  `import { createPersianLabsIcon } from "../../../create-persian-labs-icon";`,
  `import { data } from "../data";`,
  ``,
];
for (const icon of icons) {
  lines.push(
    `export const ${icon.componentName} = createPersianLabsIcon(${serialize(icon.id)}, ${serialize(icon.componentName)}, data[${serialize(icon.id)}]!);`,
  );
}
lines.push("");
await writeFile(join(outRoot, "icons", "index.tsx"), lines.join("\n"));

await writeFile(
  join(outRoot, "index.ts"),
  `// Generated by scripts/generate-logos-per-service.mjs — do not edit.\n` +
    `export { logosPerServiceCategory, logosPerServiceManifest } from "./catalog";\n` +
    `export { data as logosPerServiceData } from "./data";\n`,
);

flushComponentRegistry();
console.log(`Generated ${icons.length} logos-per-service icons`);
console.log(`Output: ${outRoot}`);
